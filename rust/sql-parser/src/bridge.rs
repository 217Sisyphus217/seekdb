    struct Node {
        kind: NodeKind,
        children: Vec<Node>,
        text: String,
        start: usize,
        end: usize,
        value: u64,
        depth: usize,
    }

    struct ParseTree {
        root: Node,
        expanded_sql: String,
        parameters: usize,
        parameter_names: Vec<String>,
        error: String,
        error_offset: usize,
    }

